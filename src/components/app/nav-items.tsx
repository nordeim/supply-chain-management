/**
 * Active-section predicate: exact match for the dashboard, path-segment
 * prefix match (with the slash boundary) for every other section — a
 * detail route keeps its section highlighted in both navs.
 */
export function isNavItemActive(pathname: string, href: string): boolean {
  if (href === '/') return pathname === '/';
  return pathname === href || pathname.startsWith(`${href}/`);
}

